export const issueSection = (issue: number) => copy.issues.find((i) => i.id === issue)!.section;

export const active = (cs: Collaborator[]) => cs.filter((c) => !isGhost(c));
export const firstOf = (cs: Collaborator[], role: AgentRole) =>
  active(cs).filter((c) => c.role === role).sort((a, b) => a.addedAt - b.addedAt)[0];

export function defaultName(role: AgentRole, otherType?: string) {
  // A human teammate is a real person: no made-up default, the user types the name.
  if (role === 'teammate') return '';
  if (role === 'other' && otherType && otherType !== 'Custom…') {
    return t(copy.constellation.otherDefaultName, { type: otherType });
  }
  return copy.roles[role].defaultName;
}

/** Auto-connect rules (flow-and-milestones.md): prefilled into CONNECTS TO, still toggleable. */
export function defaultConnects(role: AgentRole, cs: Collaborator[]): string[] {
  const builder = firstOf(cs, 'builder');
  const reviewer = firstOf(cs, 'reviewer');
  const list = active(cs);
  switch (role) {
    case 'builder':
      return [
        'you',
        ...(reviewer ? [reviewer.id] : []),
        // Other agents added before any builder pick it up now.
        ...list.filter((c) => c.role === 'other' && !list.some((b) => b.role === 'builder' && c.connectsTo.includes(b.id))).map((c) => c.id),
      ];
    case 'reviewer':
      return [
        'you',
        ...(builder ? [builder.id] : []),
        ...list.filter((c) => c.role === 'tester' && !list.some((r) => r.role === 'reviewer' && c.connectsTo.includes(r.id))).map((c) => c.id),
      ];
    case 'tester':
      return reviewer ? [reviewer.id] : ['you'];
    case 'teammate':
      return ['you'];
    case 'other':
      return ['you', ...(builder ? [builder.id] : [])];
  }
}

/** A collaborator with no lines left (e.g. its reviewer was removed) falls back to You. */
function reattachOrphans(cs: Collaborator[]): Collaborator[] {
  return cs.map((c) => {
    const linked = c.connectsTo.length > 0 || cs.some((o) => o.connectsTo.includes(c.id));
    return linked ? c : { ...c, connectsTo: ['you'] };
  });
}

function roleMilestones(cs: Collaborator[], m: Milestones): Milestones {
  const list = active(cs);
  return {
    ...m,
    builderAdded: m.builderAdded || list.some((c) => c.role === 'builder'),
    reviewerAdded: m.reviewerAdded || list.some((c) => c.role === 'reviewer'),
  };
}

export const useScenario = create<ScenarioState>()(
  persist(
    (set, get) => ({
      collaborators: [],
      milestones: NO_MILESTONES,
      recommendation: 'none',
      files: {},
      fileDrafts: {},
      sections: initialSections(),
      issues: initialIssues(),
      pr: { title: copy.pullRequest.titleValue, description: copy.pullRequest.descriptionValue, reviewer: null, attachReceipt: true },
      thread: [],
      reviewStage: 'none',
      commentAt: 0,
      firstAdded: false,
      view: IDENTITY_VIEW,
      seq: 1,
      addMenu: null,
      configure: null,
      popover: null,
      hoverId: null,
      specOpen: false,
      replies: [],
      readyVisible: false,
      updateCardOpen: true,
      recCardOpen: false,
      floatingFile: null,
      floatingSettled: 0,
      sectionsLine: null,
      editor: null,
      linkIds: null,
      cardNotes: {},
      rightPanel: null,
      commentOpen: false,
      stageWidth: 1440,
      allClearOpen: false,
      composerTarget: 'team',
      attachments: [],
      commentWith: null,

      openAddMenu: (anchor, highlight) => set({ addMenu: { anchor, highlight }, popover: null }),
      closeAddMenu: () => set({ addMenu: null }),

      startDraft: (role, otherType) => {
        const { collaborators, seq } = get();
        const kept = collaborators.filter((c) => c.status !== 'draft');
        const id = `${role}-${seq}`;
        const draft: Collaborator = {
          id,
          role,
          name: defaultName(role, otherType),
          otherType: role === 'other' ? otherType ?? copy.roles.other.subtypes[0] : undefined,
          configuration: role === 'teammate' ? '' : copy.roles[role].defaultConfig ?? copy.configurePanel.fields.configurationOptions[0],
          allowedToEdit: [...((copy.roles[role] as { allowedToEdit?: string[] }).allowedToEdit ?? [])],
          crossTeamRequests: false,
          connectsTo: defaultConnects(role, kept),
          status: 'draft',
          addedAt: Date.now(),
          slot: pickSlot(role, kept.map((c) => c.slot)),
        };
        set({
          collaborators: [...kept, draft],
          seq: seq + 1,
          addMenu: null,
          popover: null,
          configure: { id, mode: 'new', focusName: false },
        });
      },

      editCollaborator: (id, opts = {}) =>
        set((s) => ({
          collaborators: s.collaborators.filter((c) => c.status !== 'draft'),
          configure: { id, mode: 'edit', focusName: !!opts.focusName, prefillName: opts.prefillName },
          popover: null,
          addMenu: null,
        })),

      updateDraft: (patch) =>
        set((s) => ({
          collaborators: s.collaborators.map((c) => (c.id === s.configure?.id && c.status === 'draft' ? { ...c, ...patch } : c)),
        })),

      commitConfigure: (form) => {
        const { configure, collaborators, milestones } = get();
        if (!configure) return;
        const target = collaborators.find((c) => c.id === configure.id);
        if (!target) return set({ configure: null });
        const name = form.name?.trim() || defaultName(target.role, form.otherType ?? target.otherType);
        const next = reattachOrphans(
          collaborators.map((c) =>
            c.id === target.id
              ? { ...c, ...form, name, status: c.status === 'draft' ? 'active' : c.status }
              // Dropping a connection in CONNECTS TO removes it from both ends.
              : form.connectsTo && !form.connectsTo.includes(c.id) && c.connectsTo.includes(target.id)
                ? { ...c, connectsTo: c.connectsTo.filter((x) => x !== target.id) }
                : c,
          ),
        );
        set({ collaborators: next, configure: null, firstAdded: true, milestones: roleMilestones(next, milestones) });
      },

      cancelConfigure: () =>
        set((s) => ({ collaborators: s.collaborators.filter((c) => c.status !== 'draft'), configure: null })),

      removeCollaborator: (id) =>
        set((s) => ({
          collaborators: reattachOrphans(
            s.collaborators.filter((c) => c.id !== id).map((c) => ({ ...c, connectsTo: c.connectsTo.filter((x) => x !== id) })),
          ),
          popover: null,
        })),

      openPopover: (id) => set({ popover: id, addMenu: null }),
      setHoverId: (id) => set({ hoverId: id }),
      setSpecOpen: (open) => set({ specOpen: open, popover: null }),
      setView: (view) => set({ view }),

      setReadyVisible: (v) => set({ readyVisible: v }),

      startBuild: () => {
        const { milestones, collaborators } = get();
        if (milestones.buildStarted) return;
        const builder = firstOf(collaborators, 'builder');
        if (!builder) return;
        set({
          milestones: { ...milestones, buildStarted: true },
          files: seedFiles(builder.name),
          fileDrafts: {},
          updateCardOpen: true,
        });
      },
      setUpdateCardOpen: (v) => set({ updateCardOpen: v }),

      // M4: the builder and reviewer line turns red. A pending tester suggestion quietly expires.
      raiseIssue: () =>
        set((s) => ({
          milestones: { ...s.milestones, issueRaised: true },
          recommendation: s.recommendation === 'shown' || s.recommendation === 'dismissed' ? 'expired' : s.recommendation,
          recCardOpen: false,
          sections: Object.keys(s.sections).length ? s.sections : initialSections(),
          issues: Object.keys(s.issues).length ? s.issues : initialIssues(),
        })),

      openSections: (line) => {
        const s = get();
        const b = firstOf(s.collaborators, 'builder');
        const r = firstOf(s.collaborators, 'reviewer');
        const fallback: [string, string] | null = b && r ? [b.id, r.id] : null;
        set({
          sectionsLine: line ?? fallback,
          milestones: { ...s.milestones, sectionsOpened: true },
          popover: null,
          addMenu: null,
          floatingFile: null,
          updateCardOpen: false,
        });
      },
      closeSections: () => set({ sectionsLine: null, linkIds: null }),

      openSection: (id, tab) => {
        const s = get();
        if (!s.sectionsLine && !s.milestones.allSectionsVerified) get().openSections();
        set({ editor: { section: id, tab: tab ?? sectionById(id).file, mode: 'edit' }, linkIds: null, popover: null, cardNotes: {} });
      },
      closeEditor: () => set({ editor: null }),
      setEditorMode: (mode) => set((s) => (s.editor ? { editor: { ...s.editor, mode } } : {})),
      setEditorTab: (tab) => set((s) => (s.editor ? { editor: { ...s.editor, tab } } : {})),

      saveSectionFile: (file) => {
        const s = get();
        const draft = s.fileDrafts[file];
        const { [file]: _, ...rest } = s.fileDrafts;
        const text = draft ?? s.files[file];
        // A section is edited by you when its own lines differ from the builder's original.
        const sections = { ...s.sections };
        if (draft !== undefined) {
          const builder = firstOf(s.collaborators, 'builder');
          const original = originalFile(file, builder?.name ?? 'Builder');
          const mine = changedLines(original, text);
          for (const [id, st] of Object.entries(sections)) {
            const def = sectionById(id);
            if (!def.files.includes(file) || st.editedByYou) continue;
            const whole = def.files.length > 1 || ['contractTests', 'changelog'].includes(id);
            const r = whole ? { start: 1, end: text.split('\n').length } : safeRange(id, text);
            if ([...mine].some((n) => n >= r.start && n <= r.end)) sections[id] = { ...st, editedByYou: true };
          }
        }
        // Issues whose code lives in this file go back to both agents (flow-and-milestones: Save to recheck).
        const waiting = Object.values(s.issues)
          .filter((i) => (i.status === 'open' || i.status === 'savedAwaitingAgents') && sectionById(issueSection(i.id)).files.includes(file))
          .map((i) => i.id);
        const issues = { ...s.issues };
        for (const id of waiting) issues[id] = { ...issues[id], status: 'savedAwaitingAgents', note: undefined };
        set({
          files: { ...s.files, [file]: text },
          fileDrafts: rest,
          sections,
          issues,
          milestones: { ...s.milestones, sectionSaved: true },
        });
        return waiting;
      },

      recheck: (ids) => {
        const s = get();
        const issues = { ...s.issues };
        for (const id of ids) {
          const i = issues[id];
          if (!i || i.status !== 'savedAwaitingAgents') continue;
          const file = sectionById(issueSection(id)).file;
          issues[id] = issueMet(id, s.files[file] ?? '')
            ? { id, status: 'resolved', how: 'edited' }
            : { id, status: 'open', note: t((copy.editor.notStillMet as Record<string, { text: string }>)[String(id)]) };
        }
        set({ issues });
      },

      acceptFix: (issue) => {
        const s = get();
        const file = sectionById(issueSection(issue)).file;
        const current = s.fileDrafts[file] ?? s.files[file] ?? '';
        const { [file]: _, ...rest } = s.fileDrafts;
        set({
          files: { ...s.files, [file]: applyFix(issue, current) },
          fileDrafts: rest,
          issues: { ...s.issues, [issue]: { id: issue, status: 'resolved', how: 'accepted' } },
          editor: s.editor ? { ...s.editor, mode: 'edit' } : null,
        });
      },

      rejectIssue: (issue) =>
        set((s) => ({
          issues: { ...s.issues, [issue]: { id: issue, status: 'rejected', how: 'rejected' } },
          editor: s.editor ? { ...s.editor, mode: 'edit' } : null,
        })),

      verifySection: (id) => {
        const s = get();
        const sections = { ...s.sections, [id]: { ...s.sections[id], status: 'verified' as const } };
        // A parent (createPlan) is verified once all its subsections are.
        const parent = sectionById(id).parent;
        if (parent) {
          const kids = sectionById(parent).children ?? [];
          if (kids.every((k) => sections[k].status === 'verified')) sections[parent] = { ...sections[parent], status: 'verified' };
        }
        set({ sections });
      },

      setLinkIds: (ids) => set({ linkIds: ids }),
      setCardNote: (role, text) => set((s) => ({ cardNotes: { ...s.cardNotes, [role]: text } })),

      setStageWidth: (w) => set({ stageWidth: w }),
      setAllClearOpen: (v) => set({ allClearOpen: v }),
      setComposerTarget: (target) => set({ composerTarget: target }),
      setAttachments: (files) => set({ attachments: files }),
      openThread: (teammateId) => set({ commentWith: teammateId, commentOpen: true, popover: null }),
      // Messages to a teammate outside the review get a short scripted answer (useReviewFlow).
      messageTeammate: (teammateId, text) =>
        set((s) => ({
          thread: [...s.thread, { from: 'you', text, with: teammateId, attachments: s.attachments.length ? s.attachments : undefined }],
          attachments: [],
          commentWith: teammateId,
          commentOpen: true,
        })),
      setReviewStage: (stage) =>
        set((s) => ({
          reviewStage: stage,
          commentOpen: stage === 'commented' ? true : s.commentOpen,
          commentWith: stage === 'commented' ? s.pr.reviewer : s.commentWith,
          commentAt: stage === 'commented' && s.reviewStage !== 'commented' ? s.thread.length : s.commentAt,
        })),
      setRightPanel: (p) => set({ rightPanel: p, sectionsLine: null, popover: null, updateCardOpen: false }),

      // M8: the PR panel. Without a teammate, Dana Kim appears as a dashed "adding" ghost (frame 09).
      openPR: () => {
        const s = get();
        let collaborators = s.collaborators;
        let reviewer = s.pr.reviewer && collaborators.some((c) => c.id === s.pr.reviewer) ? s.pr.reviewer : null;
        const mates = collaborators.filter((c) => c.role === 'teammate');
        if (!reviewer && mates.length) reviewer = mates[0].id;
        let seq = s.seq;
        if (!reviewer) {
          const ghost: Collaborator = {
            id: `teammate-${seq}`,
            role: 'teammate',
            name: copy.people.teammate.fullName,
            email: t(copy.people.teammate.email),
            configuration: '',
            allowedToEdit: [],
            crossTeamRequests: false,
            connectsTo: ['you'],
            status: 'suggested',
            addedAt: Date.now(),
            slot: pickSlot('teammate', collaborators.map((c) => c.slot)),
          };
          collaborators = [...collaborators, ghost];
          reviewer = ghost.id;
          seq += 1;
        }
        set({
          collaborators,
          seq,
          pr: { ...s.pr, reviewer },
          rightPanel: 'pr',
          sectionsLine: null,
          editor: null,
          popover: null,
          milestones: { ...s.milestones, prOpened: true },
        });
      },
      // Closing the PR panel takes the ghost with it and goes back to the receipt.
      closePR: () =>
        set((s) => ({
          collaborators: s.collaborators.filter((c) => c.status !== 'suggested'),
          rightPanel: 'receipt',
        })),
      setPR: (patch) => set((s) => ({ pr: { ...s.pr, ...patch } })),

      // M9: the PR exists; the teammate joins (or is already there) and starts reviewing.
      createPR: () => {
        const s = get();
        const id = s.pr.reviewer;
        set({
          collaborators: s.collaborators.map((c) =>
            c.id === id ? { ...c, status: 'active', review: 'pending', connectsTo: c.connectsTo.includes('you') ? c.connectsTo : [...c.connectsTo, 'you'] } : c,
          ),
          rightPanel: null,
          // The comment arrives after the teammate has looked at the PR (useReviewFlow).
          commentOpen: false,
          commentWith: id,
          reviewStage: 'reviewing',
          firstAdded: true,
          milestones: { ...s.milestones, prCreated: true },
        });
      },
      setCommentOpen: (v) => set({ commentOpen: v }),
      replyToTeammate: (text) =>
        set((s) => ({
          thread: [...s.thread, { from: 'you', text, with: s.pr.reviewer ?? undefined, attachments: s.attachments.length ? s.attachments : undefined }],
          attachments: [],
          reviewStage: 'reading',
          commentWith: s.pr.reviewer,
          commentOpen: true,
        })),

      // M10: approved after a reply (any text) or 20 s of quiet.
      approve: (auto) => {
        const s = get();
        if (s.milestones.teammateApproved) return;
        const tr = copy.teammateReview;
        set({
          collaborators: s.collaborators.map((c) => (c.id === s.pr.reviewer ? { ...c, review: 'approved' } : c)),
          thread: [...s.thread, { from: 'teammate', text: t(auto ? tr.autoApprove : tr.answer), with: s.pr.reviewer ?? undefined }],
          reviewStage: 'approved',
          milestones: { ...s.milestones, teammateApproved: true },
        });
      },

      // M11
      merge: () =>
        set((s) => ({
          milestones: { ...s.milestones, merged: true },
          rightPanel: 'recap',
          commentOpen: false,
        })),

      // "Show line" opens the createPlan 409 branch read-only (frame 10 to 07).
      showLine: () => {
        set({ editor: { section: 'idempotencyKey', tab: 'PlanController.java', mode: 'edit', readOnly: true }, cardNotes: {}, popover: null });
      },

      openFile: (name) =>
        set((s) => ({
          floatingFile: name,
          popover: null,
          floatingSettled: name === null && s.floatingFile ? s.floatingSettled + 1 : s.floatingSettled,
        })),
      setFileDraft: (name, text) => set((s) => ({ fileDrafts: { ...s.fileDrafts, [name]: text } })),
      saveFile: (name) =>
        set((s) => {
          const { [name]: draft, ...rest } = s.fileDrafts;
          return {
            files: draft === undefined ? s.files : { ...s.files, [name]: draft },
            fileDrafts: rest,
            floatingSettled: s.floatingSettled + 1,
          };
        }),

      setRecommendation: (r, cardOpen) =>
        set((s) => ({
          recommendation: r,
          recCardOpen: cardOpen ?? s.recCardOpen,
          milestones: r === 'shown' ? { ...s.milestones, recommendationShown: true } : s.milestones,
        })),
      setRecCardOpen: (v) => set({ recCardOpen: v, popover: null }),

      addDirect: (role) => {
        const { collaborators, seq, milestones } = get();
        const kept = collaborators.filter((c) => c.status !== 'draft');
        const c: Collaborator = {
          id: `${role}-${seq}`,
          role,
          name: defaultName(role),
          configuration: (copy.roles[role] as { defaultConfig?: string }).defaultConfig ?? '',
          allowedToEdit: [...((copy.roles[role] as { allowedToEdit?: string[] }).allowedToEdit ?? [])],
          crossTeamRequests: false,
          connectsTo: defaultConnects(role, kept),
          status: 'active',
          addedAt: Date.now(),
          slot: pickSlot(role, kept.map((x) => x.slot)),
        };
        const next = [...kept, c];
        set({ collaborators: next, seq: seq + 1, configure: null, firstAdded: true, milestones: roleMilestones(next, milestones) });
      },

      pushReply: (reply) => {
        const id = get().seq;
        set((s) => ({ seq: s.seq + 1, replies: [...s.replies, { ...reply, id }].slice(-3) }));
        return id;
      },
      updateReply: (id, patch) => set((s) => ({ replies: s.replies.map((r) => (r.id === id ? { ...r, ...patch } : r)) })),
      dismissReply: (id) => set((s) => ({ replies: s.replies.filter((r) => r.id !== id) })),
    }),
    {
      name: 'pmr:state',
      version: 2,
      // v1 (phase 1) state has no build fields; the defaults above fill them in.
      migrate: (state) => state as ScenarioState,
      storage: createJSONStorage(() => localStorage),
      partialize: (s) => ({
        collaborators: s.collaborators.filter((c) => c.status !== 'draft'),
        milestones: s.milestones,
        recommendation: s.recommendation,
        files: s.files,
        fileDrafts: s.fileDrafts,
        sections: s.sections,
        pr: s.pr,
        thread: s.thread,
        // A review stage waiting on a timer resumes as if the timer had just finished.
        reviewStage: s.reviewStage === 'reviewing' ? 'commented' : s.reviewStage === 'reading' ? 'commented' : s.reviewStage,
        commentAt: s.commentAt,
        // A recheck in flight when the page closed goes back to open; nothing is left hanging.
        issues: Object.fromEntries(
          Object.entries(s.issues).map(([k, i]) => [k, i.status === 'savedAwaitingAgents' || i.status === 'fixPreview' ? { ...i, status: 'open' as const } : i]),
        ),
        firstAdded: s.firstAdded,
        view: s.view,
        seq: s.seq,
      }),
    },
  ),
);
