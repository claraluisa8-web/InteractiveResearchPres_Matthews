function seedFiles(builderName: string): Record<string, string> {
  // Generated-by comments name the user's own builder (role, never name).
  return Object.fromEntries(SOURCE_FILES.map((f) => [f, codeFile(f).replace(/Generated by Builder/g, `Generated by ${builderName}`)]));
}

